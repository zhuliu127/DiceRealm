// ============================================================
// room_text.dart — UI 层的「空值安全取文本」唯一入口
//
// 为什么需要它：
//   domain 的 `jsStr` **必须**保持 JS 语义（`String(null) === 'null'`，
//   oracle 等价不可动）。但房间状态里有些键**允许存在且值为 null**
//   （成员裁剪、老存档迁移都会保留 `key: null`），把 `jsStr` 的结果直接
//   送进 Text / 字符串插值，界面上就会真的印出「null」，甚至带偏分支判断
//   （例如「有没有绑定角色卡」被误判成已绑定）。
//
// 口径：
//   · 渲染 / 展示 / 拼字符串 → `roomText`（null 当空串）；
//   · 需要 JS 精确语义的比较（例如 `op == 'null'` 这种守卫）→ 保留 `jsStr`。
//
// ★ 纯 Dart：只依赖 domain 的字符串转换，零 UI 框架依赖。
// ============================================================

import '../../domain/js_compat.dart' show jsStr;

/// 空值安全的取文本：`null` → `''`，其余与 `jsStr` 完全一致。
String roomText(Object? v) => v == null ? '' : jsStr(v);
